const byLang: Record<string, Map<string, string>> = {
  fr: new Map(Object.entries(FR).map(([k, v]) => [exerciseKey(k), v])),
};

/** Name to show for `language`; the stored English name when no translation is known. */
export function exerciseLabel(name: string, language: string): string {
  return byLang[language]?.get(exerciseKey(name)) ?? name;
}

export const translatedExerciseCount = (language: string) => byLang[language]?.size ?? 0;
