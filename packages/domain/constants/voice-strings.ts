const dicts: Record<string, Dict> = { en, fr, es, pt, de, ar };

export function voiceText(lang: string, key: VoiceKey, vars: Record<string, string | number> = {}): string {
  const raw = dicts[lang]?.[key] ?? en[key];
  return raw.replace(/\{(\w+)\}/g, (_m, name: string) => String(vars[name] ?? ''));
}

/** "a, b and c" in the given language. */
export function joinList(lang: string, items: string[]): string {
  if (items.length <= 1) return items.join('');
  return `${items.slice(0, -1).join(', ')} ${voiceText(lang, 'and')} ${items[items.length - 1]}`;
}

export const EXAMPLE_GROUPS = ['style', 'meals', 'fitness', 'nav'] as const;
export type ExampleGroup = (typeof EXAMPLE_GROUPS)[number];
/** Real, parseable example commands for a workspace (see voice-execute tests). */
export function voiceExamples(lang: string, group: ExampleGroup): string[] {
  return voiceText(lang, `ex_${group}` as VoiceKey).split('|');
}
/** Three examples tailored to the area the unknown phrase seems to be about. */
export function examplesForArea(lang: string, area: 'style' | 'meals' | 'fitness' | 'general'): string[] {
  if (area === 'general')
    return [
      voiceExamples(lang, 'meals')[0],
      voiceExamples(lang, 'fitness')[0],
      voiceExamples(lang, 'style')[0],
    ];
  return voiceExamples(lang, area).slice(0, 3);
}
